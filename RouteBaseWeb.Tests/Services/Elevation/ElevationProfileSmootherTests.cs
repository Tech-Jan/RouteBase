    private static double TotalVariation(double[] a)
    {
        double tv = 0;
        for (int i = 1; i < a.Length; i++) tv += Math.Abs(a[i] - a[i - 1]);
        return tv;
    }

    [Fact]
    public void Lambda_MatchesLengthFormula()
    {
        Assert.Equal(Math.Pow(21.0, 4.0), ElevationProfileSmoother.Lambda(105.0, 5.0), precision: 6);
        Assert.Equal(194481.0, ElevationProfileSmoother.Lambda(105.0, 5.0), precision: 6);
    }

    [Fact]
    public void Whittaker_Constant_ReturnsConstant()
    {
        var y = Enumerable.Repeat(7.0, 20).ToArray();
        var x = ElevationProfileSmoother.WhittakerSecondOrder(y, 30.0);
        Assert.All(x, v => Assert.Equal(7.0, v, precision: 9));
    }

    [Fact]
    public void Whittaker_Line_ReturnsLine()
    {
        // A straight line has zero 2nd difference, so a curvature penalty leaves it untouched.
        var y = Enumerable.Range(0, 12).Select(i => 5.0 + 3.0 * i).ToArray();
        var x = ElevationProfileSmoother.WhittakerSecondOrder(y, 1000.0);
        for (int i = 0; i < y.Length; i++) Assert.Equal(y[i], x[i], precision: 6);
    }

