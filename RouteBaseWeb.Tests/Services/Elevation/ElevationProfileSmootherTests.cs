    [Fact]
    public void Whittaker_ReducesNoiseTotalVariation()
    {
        var rng = new Random(0);
        var baseSignal = Enumerable.Range(0, 400).Select(i => i * 0.25).ToArray();
        var noisy = baseSignal.Select(v => v + (rng.NextDouble() - 0.5) * 8.0).ToArray();
        var x = ElevationProfileSmoother.WhittakerSecondOrder(noisy, ElevationProfileSmoother.Lambda(105, 5));
        Assert.True(TotalVariation(x) < 0.4 * TotalVariation(noisy),
            "Curvature smoother should strip most of the high-frequency total variation");
    }

    [Fact]
    public void SmoothByArcLength_ShortTrack_ReturnsUnchanged()
    {
        var arc = new[] { 0.0, 3.0, 6.0, 9.0 };            // < 5 grid steps at ds = 5 m
        var alt = new[] { 100.0, 130.0, 100.0, 130.0 };
        var x = ElevationProfileSmoother.SmoothByArcLength(arc, alt);
        Assert.Equal(alt, x);
    }

    [Fact]
    public void SmoothByArcLength_StripsSubResolutionJitter()
    {
        // A ~100 m climb with saw-tooth jitter every metre: smoothing must cut the phantom gain while
        // keeping the real climb (endpoints preserved to within a few metres of the underlying trend).
        int n = 400;
        var arc = new double[n];
        var alt = new double[n];
        for (int i = 0; i < n; i++)
        {
            arc[i] = i * 1.0;                               // 1 m spacing, 400 m long
            alt[i] = 100.0 + i * 0.25 + (i % 2 == 0 ? 3.0 : -3.0);  // +~100 m real climb + ±3 m jitter
        }
        var x = ElevationProfileSmoother.SmoothByArcLength(arc, alt);
        Assert.True(TotalVariation(x) < 0.5 * TotalVariation(alt), "Phantom jitter gain should drop sharply");
        Assert.True(Math.Abs(x[0] - 100.0) < 4.0, $"start near the trend; got {x[0]:F1}");
        Assert.True(Math.Abs(x[^1] - 199.75) < 4.0, $"end near the trend; got {x[^1]:F1}");
        Assert.True(x[^1] > x[0] + 90.0, "The real ~100 m climb must survive");
    }

    [Fact]
    public void Relief_IsPopulationStd()
    {
        // np.std([1,2,3,4]) = sqrt(1.25) — the harness convention the flat threshold was tuned with.
        Assert.Equal(Math.Sqrt(1.25), ElevationProfileSmoother.Relief(new[] { 1.0, 2.0, 3.0, 4.0 }), precision: 12);
        Assert.Equal(0.0, ElevationProfileSmoother.Relief(Array.Empty<double>()));
    }

    private static (double[] arc, double[] alt) NoisyTrack(double slopePerPoint)
    {
        var rng = new Random(42);
        int n = 600;                                       // 3 km at 5 m spacing
        var arc = new double[n];
        var alt = new double[n];
        for (int i = 0; i < n; i++)
        {
            arc[i] = i * 5.0;
            alt[i] = 300.0 + i * slopePerPoint + (rng.NextDouble() - 0.5) * 4.0;   // ±2 m DEM noise
        }
        return (arc, alt);
    }

    [Fact]
    public void SmoothByArcLength_DeadFlatTrack_EngagesFlatRegime()
    {
        // Dead flat: smoothed relief ≪ 8 m → the default call must produce the L=200 result.
        // (An explicit L=200 call re-selects L=200 in the flat branch, so it is a fixed point.)
        var (arc, alt) = NoisyTrack(slopePerPoint: 0.0);
        var byDefault = ElevationProfileSmoother.SmoothByArcLength(arc, alt);
        var atFlatLength = ElevationProfileSmoother.SmoothByArcLength(
            arc, alt, ElevationProfileSmoother.FlatSmoothLengthMeters);
        Assert.Equal(atFlatLength, byDefault);
        Assert.True(TotalVariation(byDefault) < TotalVariation(alt) * 0.05,
            "flat regime should crush nearly all noise variation");
    }

    [Fact]
    public void SmoothByArcLength_ClimbingTrack_KeepsDefaultRegime()
    {
        // ~90 m climb over 3 km → smoothed relief ~26 m > 8 m: stays at L=105 (differs from L=200).
        var (arc, alt) = NoisyTrack(slopePerPoint: 0.15);
        var byDefault = ElevationProfileSmoother.SmoothByArcLength(arc, alt);
        var atFlatLength = ElevationProfileSmoother.SmoothByArcLength(
            arc, alt, ElevationProfileSmoother.FlatSmoothLengthMeters);
        Assert.NotEqual(atFlatLength, byDefault);
        Assert.True(byDefault[^1] > byDefault[0] + 80.0, "the real climb must survive");
    }

    [Fact]
    public void InterpLinear_InterpolatesAndClamps()
    {
        var xp = new[] { 0.0, 10.0, 20.0 };
        var fp = new[] { 0.0, 100.0, 50.0 };
        var q = ElevationProfileSmoother.InterpLinear(xp, fp, new[] { -5.0, 5.0, 15.0, 25.0 });
        Assert.Equal(0.0, q[0], precision: 9);    // clamped low
        Assert.Equal(50.0, q[1], precision: 9);   // midpoint 0..100
        Assert.Equal(75.0, q[2], precision: 9);   // midpoint 100..50
        Assert.Equal(50.0, q[3], precision: 9);   // clamped high
    }
