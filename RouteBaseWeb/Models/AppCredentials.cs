using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace RouteBaseWeb.Models;

/// <summary>
/// Unified credentials table replacing the separate StravaToken,
/// StravaCredentials and MapTilerCredentials tables.
/// The Type column identifies which credential set the row belongs to.
/// </summary>
[Table("AppCredentials")]
public class AppCredentials
{
    [Key]
    public int Id { get; set; }

    /// <summary>
    /// "StravaToken" | "StravaCredentials" | "MapTilerCredentials"
    /// </summary>
    [Required]
    [MaxLength(50)]
    public string Type { get; set; } = string.Empty;

    // ?? Strava OAuth token ??????????????????????????????????????
    public string? AccessToken { get; set; }
    public string? RefreshToken { get; set; }
    public DateTime? ExpiresAt { get; set; }
    public long? AthleteId { get; set; }

    // ?? Strava API credentials ??????????????????????????????????
    [MaxLength(100)]
    public string? ClientId { get; set; }

    [MaxLength(255)]
    public string? ClientSecret { get; set; }

    // ?? MapTiler API key ????????????????????????????????????????
    [MaxLength(255)]
    public string? ApiKey { get; set; }

    // ?? User ownership ????????????????????????????????????????????
    [Column("user_id")]
    public string? UserId { get; set; }

    [ForeignKey("UserId")]
    public virtual AppUser? User { get; set; }

    // ?? Audit ???????????????????????????????????????????????????
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
}

public static class CredentialTypes
{
    public const string StravaToken         = "StravaToken";
    public const string StravaCredentials   = "StravaCredentials";
    public const string MapTilerCredentials = "MapTilerCredentials";
    public const string MobileApiKey        = "MobileApiKey";
}
